/**
 * The Vocab Lavender palette. Names and values match the design system's tokens.json,
 * so a token renamed there is renamed here.
 */
@Immutable
data class VocabColors(
    val canvas: Color,
    val surface: Color,
    val surfaceAlt: Color,
    val surfaceSunk: Color,
    val line: Color,
    val ink: Color,
    val inkMuted: Color,
    val primary: Color,
    val primaryStrong: Color,
    val onPrimary: Color,
    val primaryDeep: Color,
    val primarySoft: Color,
    val primaryText: Color,
    val go: Color,
    val onGo: Color,
    val goDeep: Color,
    val butter: Color,
    val butterSoft: Color,
    val butterInk: Color,
    val lilac: Color,
    val lilacSoft: Color,
    val lilacInk: Color,
    val mint: Color,
    val mintSoft: Color,
    val sky: Color,
    val skySoft: Color,
    val skyInk: Color,
    val periwinkle: Color,
    val pink: Color,
    val peach: Color,
    val peachSoft: Color,
    val peachInk: Color,
    val chipInk: Color,
    val correct: Color,
    val correctSoft: Color,
    val wrong: Color,
    val wrongSoft: Color,
    val star: Color,
    val streak: Color,
    val streakSoft: Color,
    val streakInk: Color,
    val focus: Color,
    val artShadow: Color,
    val heroTrack: Color,
    val isDark: Boolean,
) {
    fun topic(color: TopicColor): Color = when (color) {
        TopicColor.PERIWINKLE -> periwinkle
        TopicColor.MINT -> mint
        TopicColor.BUTTER -> butter
        TopicColor.PINK -> pink
        TopicColor.SKY -> sky
        TopicColor.LILAC -> lilac
    }
}

